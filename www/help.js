// ---- fallback content for any route without a dedicated entry ----
function helpForRoute(route) {
  if (HELP[route]) return HELP[route];
  var map = { order: 'orders', quote: 'quotes', lead: 'leads', project: 'projects', company: 'companies' };
  if (map[route]) return HELP[map[route]];
  return HELP.more;
}

// ---- build modal body from a help entry ----
function helpBody(entry) {
  var body = '';
  entry.rows.forEach(function (r) {
    body += '<div style="margin-bottom:.7rem"><label>' + esc(r[0]) + '</label>' +
      '<p style="margin:.15rem 0 0;line-height:1.8">' + esc(r[1]) + '</p></div>';
  });
  if (entry.example) {
    body += '<div class="card" style="background:var(--primary-soft);border-color:var(--primary)">' +
      '<b style="font-size:var(--fs-caption);color:var(--primary-hover)">مثال واقعی</b>' +
      '<p style="margin:.3rem 0 0;line-height:1.8">' + esc(entry.example) + '</p></div>';
  }
  body += '<button class="btn btn-block" id="help-close">متوجه شدم</button>';
  return body;
}

// ---- open the real modal for the current route ----
function openHelp(route) {
  var entry = helpForRoute(route);
  modal(entry.title, helpBody(entry), function () {
    var b = document.getElementById('help-close');
    if (b) b.onclick = function () {
      if (typeof closeModal === 'function') closeModal();
      else document.getElementById('modal-root').innerHTML = '';
    };
  });
}

// ============ VISIBLE HELP BUTTON (two independent paths) ============

// Path 1: button inside the top bar, re-ensured after every render.
function ensureHelpButton() {
  var bar = document.getElementById('topbar');
  if (!bar) { ensureFallbackButton(); return; }
  var existing = document.getElementById('btn-help');
  if (existing && bar.contains(existing)) return;
  if (existing && existing.parentNode) existing.parentNode.removeChild(existing);
  var btn = document.createElement('button');
  btn.className = 'icon-btn';
  btn.id = 'btn-help';
  btn.type = 'button';
  btn.setAttribute('aria-label', 'راهنمای این صفحه');
  btn.setAttribute('title', 'راهنمای این صفحه');
  btn.innerHTML = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><circle cx="12" cy="12" r="10"/><path d="M9.09 9a3 3 0 0 1 5.83 1c0 2-3 3-3 3"/><path d="M12 17h.01"/></svg>';
  btn.onclick = function () { openHelp(currentRouteSafe()); };
  var back = document.getElementById('btn-back');
  if (back && back.parentNode === bar) bar.insertBefore(btn, back.nextSibling);
  else bar.insertBefore(btn, bar.firstChild);
  removeFallbackButton();
}

// Path 2: floating fallback — only when the top bar cannot host the button.
function ensureFallbackButton() {
  if (document.getElementById('btn-help')) return;
  var old = document.getElementById('btn-help-float');
  if (old) old.remove();
  var btn = document.createElement('button');
  btn.id = 'btn-help-float';
  btn.type = 'button';
  btn.setAttribute('aria-label', 'راهنمای این صفحه');
  btn.style.cssText = 'position:fixed;top:calc(env(safe-area-inset-top) + .5rem);inset-inline-start:.5rem;z-index:70;' +
    'width:44px;height:44px;border-radius:50%;border:1px solid var(--border-strong);background:var(--surface);' +
    'color:var(--primary-hover);box-shadow:var(--shadow-2);display:flex;align-items:center;justify-content:center;cursor:pointer';
  btn.innerHTML = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" style="width:22px;height:22px" stroke-linecap="round" stroke-linejoin="round"><circle cx="12" cy="12" r="10"/><path d="M9.09 9a3 3 0 0 1 5.83 1c0 2-3 3-3 3"/><path d="M12 17h.01"/></svg>';
  btn.onclick = function () { openHelp(currentRouteSafe()); };
  document.body.appendChild(btn);
}
function removeFallbackButton() {
  var f = document.getElementById('btn-help-float');
  if (f) f.remove();
}

// read the current route even before app.js globals are visible
function currentRouteSafe() {
  try {
    if (typeof currentRoute === 'string' && currentRoute) return currentRoute;
  } catch (e) { /* not defined yet */ }
  var h = (location.hash || '').replace('#', '');
  var base = h ? h.split('/')[0] : '';
  return base || 'today';
}

// run the ensure check at safe moments: ready + after every render + on hash change
function startHelpSystem() {
  ensureHelpButton();
  if (typeof window.render === 'function' && !window.render.__helpWrapped) {
    var orig = window.render;
    var wrapped = function () {
      var out = orig.apply(this, arguments);
      ensureHelpButton();
      return out;
    };
    wrapped.__helpWrapped = true;
    window.render = wrapped;
  }
  window.addEventListener('hashchange', ensureHelpButton);
  window.addEventListener('load', ensureHelpButton);
}
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', startHelpSystem);
} else {
  startHelpSystem();
}
// late re-try for slow environments (idempotent, cheap)
setTimeout(startHelpSystem, 400);
setTimeout(startHelpButtonLate, 1500);
function startHelpButtonLate() { ensureHelpButton(); }